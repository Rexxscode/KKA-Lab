        <h4 class="font-extrabold text-slate-900">1. Apa itu AI?</h4>
        <p><b>Artificial Intelligence (Kecerdasan Artifisial)</b> adalah sistem komputer yang dirancang meniru kecerdasan manusia: mengenali pola, belajar dari pengalaman, dan mengambil keputusan. Bedanya dengan program biasa: program biasa menjalankan <b>aturan tetap</b> yang ditulis programmer, sedangkan AI <b>belajar sendiri dari data</b>.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 border border-emerald-200 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Kalkulator — hanya menghitung, bukan AI.</li>
                <li>Kamera HP yang fokus sendiri ke wajah — AI.</li>
                <li>Lampu yang menyala saat ada gerakan — bukan AI.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">2. AI Sempit vs AI Umum</h4>
        <p><b>AI sempit (narrow AI)</b> hanya pintar di satu tugas khusus. <b>AI umum</b> bisa diajak membahas apa saja seperti manusia.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 border border-emerald-200 p-3">
            <p class="font-bold">Contoh narrow AI:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Google Maps — pintar membaca peta dan jalan.</li>
                <li>Filter spam — pintar memilah email sampah.</li>
                <li>Kunci wajah HP — pintar mengenali wajah pemiliknya.</li>
            </ul>
            <p class="font-bold mt-2">Contoh AI umum:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>ChatGPT — bisa ditanya apa saja.</li>
                <li>Claude — bisa ditanya apa saja.</li>
                <li>Gemini — bisa ditanya apa saja.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">3. Machine Learning: Cara AI Belajar</h4>
        <p><b>Machine Learning</b> adalah cara AI belajar: diberi banyak <b>contoh</b>, ia mencari <b>pola</b>, lalu polanya disimpan sebagai <b>model</b>.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 border border-emerald-200 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Diberi ribuan foto kucing — jadi bisa mengenali kucing.</li>
                <li>Diberi ribuan email spam — jadi bisa menyaring spam.</li>
                <li>Diberi banyak contoh suara — jadi bisa mengetik dari suara.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">4. Data Berlabel: Kunci Jawabannya</h4>
        <p>Agar bisa belajar, data perlu <b>label</b> — keterangan yang benar. Prinsipnya: <b>banyak, beragam, dan benar labelnya</b>.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 border border-emerald-200 p-3">
            <p class="font-bold">Contoh label benar:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Foto kucing + tulisan "kucing".</li>
                <li>Foto motor + tulisan "motor".</li>
                <li>Lagu + tulisan judul dan penyanyinya.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">5. AI Bisa Salah & Peran Manusia</h4>
        <p>AI salah kalau datanya sedikit atau salah. Karena itu AI harus selalu <b>diawasi manusia</b> — manusia memegang keputusan akhir. Gunakan AI untuk <b>memahami pelajaran</b>, bukan untuk menghindari belajar.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 border border-emerald-200 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Bertanya rumus ke ChatGPT, lalu mengerjakan PR sendiri.</li>
                <li>Dokter mengecek ulang hasil diagnosa AI.</li>
                <li>Guru memeriksa kebenaran jawaban chatbot.</li>
            </ul>
        </div>
    </div>
</div>
