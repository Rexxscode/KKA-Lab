        <h4 class="font-extrabold text-slate-900">1. Apa itu AI?</h4>
        <p><b>Artificial Intelligence (Kecerdasan Artifisial)</b> adalah sistem komputer yang dirancang meniru kecerdasan manusia: mengenali pola, belajar dari pengalaman, dan mengambil keputusan. Bedanya dengan program biasa: program biasa menjalankan <b>aturan tetap</b> yang ditulis programmer (misalnya kalkulator), sedangkan AI <b>menemukan aturannya sendiri dari data</b>.</p>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">2. AI Sempit vs AI Umum</h4>
        <p>Semua AI di sekitarmu saat ini adalah <b>AI sempit (narrow AI)</b>: hebat di satu tugas spesifik — pengenalan wajah, rekomendasi film, filter spam, asisten suara — tapi tidak bisa melakukan hal lain. <b>AI umum</b> setara manusia (bisa mengerjakan apa pun, punya kesadaran) masih fiksi ilmiah.</p>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">3. Machine Learning: Cara AI Belajar</h4>
        <p><b>Machine Learning</b> adalah cara AI belajar: diberi banyak <b>contoh (data)</b>, ia mencari <b>pola</b>, lalu pola itu disimpan sebagai <b>model</b> untuk menebak data baru. Contoh: untuk mengenali kucing, AI dilatih dengan ribuan foto kucing hingga ia hafal cirinya (kumis, telinga runcing, pola bulu).</p>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">4. Data Berlabel: Kunci Jawabannya</h4>
        <p>Agar bisa belajar, data perlu <b>label</b> — keterangan yang benar, misalnya foto + tulisan "kucing". Label yang salah mengajari AI hal yang salah. Prinsipnya: <b>banyak, beragam, dan benar labelnya</b>.</p>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900">5. AI Bisa Salah & Peran Manusia</h4>
        <p>AI bukan sulap: ia salah kalau datanya sedikit, timpang, atau salah label. Karena itu AI yang bertanggung jawab selalu <b>diawasi manusia</b> — manusia memegang keputusan akhir, terutama untuk hal penting. Gunakan AI untuk <b>memahami pelajaran</b>, bukan untuk menghindari belajar.</p>
    </div>
