    <div>
        <h4 class="font-extrabold text-slate-900 dark:text-white">1. Apa itu Bias Data?</h4>
        <p><b>Bias</b> artinya kemiringan. <b>Bias data</b> terjadi saat data tidak mewakili semua kelompok secara adil. Model yang lahir dari data timpang akan timpang juga.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 dark:bg-emerald-500/10 border border-emerald-200 dark:border-emerald-500/30 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>95 foto wajah suku A, hanya 5 foto suku B.</li>
                <li>100 lagu pop, hanya 2 lagu dangdut untuk rekomendasi musik.</li>
                <li>50 foto kucing anggora, hanya 2 foto kucing kampung.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900 dark:text-white">2. Akibat di Dunia Nyata</h4>
        <p>AI dipakai untuk hal serius. Jika datanya timpang, sistem bisa <b>gagal mengenali kelompok tertentu</b>. Coba geser slider simulasi di bawah dan rasakan bedanya.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 dark:bg-emerald-500/10 border border-emerald-200 dark:border-emerald-500/30 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Absensi wajah gagal mengenali sebagian siswa.</li>
                <li>Lamaran kerja perempuan ditolak karena data lama isinya laki-laki.</li>
                <li>Asisten suara tidak paham logat daerah tertentu.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900 dark:text-white">3. Akurasi Total Bisa Menipu</h4>
        <p>Angka besar bisa menipu. Akurasi total <b>95%</b> bisa berarti sempurna di kelompok besar tapi buruk di kelompok kecil. Evaluasi yang adil selalu <b>memeriksa tiap kelompok satu per satu</b>.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 dark:bg-emerald-500/10 border border-emerald-200 dark:border-emerald-500/30 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Nilai rata-rata 95 karena 30 siswa dapat 100, padahal 2 siswa dapat 20.</li>
                <li>950 tebakan benar dari 1000 — semuanya dari kelompok yang sama.</li>
                <li>Warung "laris" karena 100 pembeli puas, padahal 900 kecewa tidak ditanya.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900 dark:text-white">4. Cara Memperbaiki</h4>
        <p>Langkahnya: <b>(1)</b> cari tahu kelompok mana yang kurang; <b>(2)</b> tambah datanya sampai seimbang; <b>(3)</b> uji tiap kelompok; <b>(4)</b> buat datamu terbuka agar bisa diperiksa orang lain.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 dark:bg-emerald-500/10 border border-emerald-200 dark:border-emerald-500/30 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Tambah 90 foto suku yang kurang.</li>
                <li>Tambah rekaman suara perempuan sampai seimbang.</li>
                <li>Tulis di laporan: datamu berisi siapa saja.</li>
            </ul>
        </div>
    </div>
    <div>
        <h4 class="font-extrabold text-slate-900 dark:text-white">5. Tanggung Jawab Manusia</h4>
        <p>AI tidak punya niat — bias berasal dari <b>pilihan data dan desain manusia</b>. Maka manusialah yang bertanggung jawab memastikan hasilnya <b>adil</b> untuk semua.</p>
        <div class="mt-2 rounded-xl bg-emerald-50 dark:bg-emerald-500/10 border border-emerald-200 dark:border-emerald-500/30 p-3">
            <p class="font-bold">Contoh:</p>
            <ul class="list-disc ps-5 mt-1 space-y-1">
                <li>Pembuat aplikasi wajib mencoba ke semua kelompok sebelum rilis.</li>
                <li>Sekolah tidak memakai absensi yang gagal untuk sebagian siswa.</li>
                <li>Kamu melaporkan bila menemukan AI yang pilih kasih.</li>
            </ul>
        </div>
